import type { ISODate } from "./dates";

export type Frequency =
  | "once"
  | "weekly"
  | "fortnightly"
  | "monthly"
  | "quarterly"
  | "half-yearly"
  | "yearly";

/** Bills and income share the same scheduling rules. */
export type ItemKind = "bill" | "income";

export interface Bill {
  id: string;
  /** Missing in data saved before income existed; treat as "bill". */
  kind?: ItemKind;
  name: string;
  /** Amount in cents. */
  amount: number;
  category: string;
  frequency: Frequency;
  /** First due date; every occurrence is computed from this. */
  anchor: ISODate;
  /** Last date the item can fall due (inclusive). */
  endDate?: ISODate;
  notes?: string;
}

/** Records that one occurrence was dealt with (paid, or received for income). Never moves the schedule. */
export interface Settlement {
  billId: string;
  /** The occurrence this settles, as generated by the item's rule. */
  due: ISODate;
  status: "paid" | "skipped";
  settledOn: ISODate;
  /** Amount in cents at the time of settling. */
  amount: number;
}

/** A one-off purchase, e.g. groceries or fuel. */
export interface Expense {
  id: string;
  name: string;
  /** Amount in cents. */
  amount: number;
  category: string;
  date: ISODate;
  notes?: string;
}

export interface AppData {
  version: 1;
  bills: Bill[];
  settlements: Settlement[];
  expenses: Expense[];
  settings: { currency: string };
}

export interface Occurrence {
  bill: Bill;
  due: ISODate;
  settlement?: Settlement;
}
