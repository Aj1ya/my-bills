import type { ISODate } from "./dates";

export type Frequency =
  | "once"
  | "weekly"
  | "fortnightly"
  | "monthly"
  | "quarterly"
  | "half-yearly"
  | "yearly";

export interface Bill {
  id: string;
  name: string;
  /** Amount in cents. */
  amount: number;
  category: string;
  frequency: Frequency;
  /** First due date; every occurrence is computed from this. */
  anchor: ISODate;
  /** Last date the bill can fall due (inclusive). */
  endDate?: ISODate;
  notes?: string;
}

/** Records that one occurrence of a bill was dealt with. Never moves the schedule. */
export interface Settlement {
  billId: string;
  /** The occurrence this settles, as generated by the bill's rule. */
  due: ISODate;
  status: "paid" | "skipped";
  settledOn: ISODate;
  /** Amount in cents at the time of settling. */
  amount: number;
}

export interface AppData {
  version: 1;
  bills: Bill[];
  settlements: Settlement[];
  settings: { currency: string };
}

export interface Occurrence {
  bill: Bill;
  due: ISODate;
  settlement?: Settlement;
}
